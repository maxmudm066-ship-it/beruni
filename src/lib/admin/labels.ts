export type TranslationKey = keyof typeof dictionary;

export function translate(locale: AdminLocale, key: TranslationKey): string {
  // Some keys are built at runtime (`type.${key}` from the content registry), so a missing
  // entry falls back to English and then to the key itself instead of throwing.
  const entry = dictionary[key] as Partial<Record<AdminLocale, string>> | undefined;
  return entry?.[locale] ?? entry?.en ?? key;
}

/** Translated message with `{name}` placeholders filled in — used by upload rejections. */
export function interpolate(
  locale: AdminLocale,
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return translate(locale, key).replace(/\{(\w+)\}/g, (whole, name: string) =>
    params[name] === undefined ? whole : String(params[name]),
  );
}

/** Workflow status shown to the administrator in their own language. */
export function statusLabel(locale: AdminLocale, status: string): string {
  return translate(locale, `status.${status}` as TranslationKey);
}

/** The language saved on an administrator's account; unknown values fall back to Russian. */
export function localeOf(language: string | null | undefined): AdminLocale {
  return (ADMIN_LOCALES as readonly string[]).includes(language ?? '') ? (language as AdminLocale) : 'ru';
}

